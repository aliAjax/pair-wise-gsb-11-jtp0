/** verify 入口：先安装 Node 环境垫片，再加载断言脚本 */
class MemoryStorage {
  constructor() {
    this.map = new Map();
  }
  getItem(key) {
    return this.map.has(key) ? this.map.get(key) : null;
  }
  setItem(key, value) {
    this.map.set(key, String(value));
  }
  removeItem(key) {
    this.map.delete(key);
  }
  clear() {
    this.map.clear();
  }
}
globalThis.localStorage = new MemoryStorage();
await import("./verify.ts");
